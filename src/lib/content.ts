type ArtistMediaItem = {
  title: string;
  meta?: string;
  cover?: string;
  href?: string;
  audioUrl?: string;
  fullAudioUrl?: string;
  src?: string;
  deezerId?: string;
  previewUrl?: string;
  durationSec?: number;
};

export function isPlayableAudioItem(item?: ArtistMediaItem | null) {
  if (!item) return false;
  if (item.audioUrl || item.fullAudioUrl || item.src || item.deezerId || item.previewUrl) return true;
  if (!item.href) return false;
  try {
    const hostname = new URL(item.href).hostname.toLowerCase();
    return (
      hostname.includes("soundcloud.com") ||
      hostname.includes("open.spotify.com") ||
      hostname.includes("deezer.com") ||
      hostname.includes("music.apple.com") ||
      hostname === "youtube.com" || hostname === "www.youtube.com" || hostname === "music.youtube.com" || hostname === "youtu.be" ||
      hostname === "spotify.link" || hostname === "on.soundcloud.com" || /\.(mp3|wav|ogg|m4a)(\?|$)/i.test(item.href)
    );
  } catch {
    return false;
  }
}

